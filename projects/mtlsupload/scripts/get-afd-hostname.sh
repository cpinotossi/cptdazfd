#!/usr/bin/env bash
# Pre-computes the deterministic Front Door default hostname of an endpoint (before the profile/endpoint exists).
# usage: get-afd-hostname.sh <endpoint-name> [scope]    scope: SubscriptionReuse (default) | TenantReuse | ResourceGroupReuse | NoReuse
set -euo pipefail
NAME="$1"; SCOPE="${2:-SubscriptionReuse}"
SUB="${AZURE_SUBSCRIPTION_ID:-$(az account show --query id -o tsv)}"
RG="${RESOURCE_GROUP:-rg-cptmtls}"
# An existing endpoint keeps its hostname, the availability API returns an empty hostname for taken names
for P in $(az afd profile list -g "$RG" --query "[].name" -o tsv); do
  H=$(az afd endpoint show -g "$RG" --profile-name "$P" --endpoint-name "$NAME" --query hostName -o tsv 2>/dev/null || true)
  [ -n "$H" ] && echo "$H" && exit 0
done
az rest --method post \
  --url "https://management.azure.com/subscriptions/$SUB/resourceGroups/$RG/providers/Microsoft.Cdn/checkEndpointNameAvailability?api-version=2024-02-01" \
  --body "{\"name\":\"$NAME\",\"type\":\"Microsoft.Cdn/Profiles/AfdEndpoints\",\"autoGeneratedDomainNameLabelScope\":\"$SCOPE\"}" \
  --query availableHostname -o tsv
